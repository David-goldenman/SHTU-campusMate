import assert from 'node:assert/strict';
import {conditionPhase,segmentHitsBounds,compileConditions,routeConditionWarnings} from '../web/conditions.js';
import {buildWalkingGraph,planWalk} from '../web/routing.js';
const point=(x,y)=>[121.6+x/95000,31.18+y/111320];
const nodes=Object.fromEntries([['a',0,0],['b',100,0],['c',100,100],['d',0,100]].map(([id,x,y])=>[id,{point:point(x,y),tags:{}}]));
const ways=[['ab','a','b'],['bc','b','c'],['cd','c','d'],['da','d','a']].map(([id,...refs])=>({id,refs,tags:{highway:'footway'}}));
const graph=buildWalkingGraph({nodes,ways});
const place=(id,x,y)=>({id,polygon:[point(x-1,y-1),point(x+1,y-1),point(x+1,y+1),point(x-1,y+1)]});
const start=place('start',10,-5),end=place('end',90,-5);
const condition={id:'test',title:'合成封闭',state:'confirmed',effect:'blocked',scope:'edges',edge_keys:['ab:a:b'],starts_on:'2026-10-17',expected_end:'2026-10-18',review_on:'2026-10-18'};
assert.equal(conditionPhase(condition,'2026-10-16'),'scheduled');
assert.equal(conditionPhase(condition,'2026-10-21'),'review_due');
let state=compileConditions(graph,[condition],'2026-10-21',[start,end]);
assert(state.blockedEdges.has('ab:a:b'),'estimated completion does not reopen a road');
const route=planWalk(state.graph,start,end);assert.equal(route.status,'ok');assert(route.segments.every(s=>s.edgeKey!=='ab:a:b'));
assert.equal(compileConditions(graph,[{...condition,state:'resolved'}],'2026-10-21',[start,end]).blockedEdges.size,0);
const pending={...condition,state:'pending'};
state=compileConditions(graph,[pending],'2026-10-21',[start,end]);assert.equal(state.blockedEdges.size,0);
assert.equal(routeConditionWarnings(planWalk(graph,start,end),state).length,1);
assert.equal(compileConditions(graph,[pending],'2026-10-21',[start,end],true).blockedEdges.size,1);
assert.equal(compileConditions(graph,[{...condition,edge_keys:['removed:node1:node2']}],'2026-10-21',[start,end]).invalid.length,1);
assert(segmentHitsBounds([0,0],[100,0],[49,-1,51,1]),'crossing a thin area with both endpoints outside must be blocked');
assert(!segmentHitsBounds([0,3],[100,3],[49,-1,51,1]));
const area={...condition,scope:'area',edge_keys:[],bounds:[...point(49,-1),...point(51,1)]};
assert(compileConditions(graph,[area],'2026-10-21',[start,end]).blockedEdges.has('ab:a:b'));
const closedPlace={...condition,scope:'place',place_id:'end',edge_keys:[]};
assert(compileConditions(graph,[closedPlace],'2026-10-21',[start,end]).blockedPlaces.has('end'));
const closedSite={...area,bounds:[...point(85,-10),...point(95,0)]};
assert(compileConditions(graph,[closedSite],'2026-10-21',[start,end]).blockedPlaces.has('end'),'a destination inside a closed site cannot snap to an outside road');
assert(!segmentHitsBounds([0,0],[100,0],[]));
console.log('campus-map conditions: scheduled/review states, closed-road routing, cautious pending opt-in, bounds intersection, invalid targets and closed destinations passed');
